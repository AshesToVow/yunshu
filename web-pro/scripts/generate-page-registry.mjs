/**
 * 扫描 src/pages 下 *-page.tsx，重新生成 legacy-page-registry.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PAGES_ROOT = path.resolve(__dirname, '../src/pages');
const OUT = path.resolve(__dirname, '../src/utils/legacy-page-registry.ts');

function walkPages(dir, base = '') {
  const out = [];
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const rel = base ? `${base}/${name}` : name;
    if (fs.statSync(full).isDirectory()) {
      out.push(...walkPages(full, rel));
    } else if (/-page\.tsx$/i.test(name)) {
      out.push(rel.replace(/\\/g, '/').replace(/\.tsx$/i, ''));
    }
  }
  return out;
}

function toExportName(fileBase) {
  return fileBase
    .split('/')
    .pop()
    .split('-')
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join('');
}

const pageIds = walkPages(PAGES_ROOT).sort();
const entries = pageIds
  .map((id) => {
    const exportName = toExportName(id);
    return `  '${id}': () => import('../pages/${id}').then((m) => resolveExport(m, '${exportName}')),`;
  })
  .join('\n');

const content = `/** auto-generated by scripts/generate-page-registry.mjs — do not edit */
import { lazy, type ComponentType, type LazyExoticComponent } from 'react';

function resolveExport(mod: Record<string, unknown>, exportName: string): { default: ComponentType<object> } {
  const direct = mod[exportName] as ComponentType<object> | undefined;
  const fallback = mod.default as ComponentType<object> | undefined;
  const pageLike = Object.entries(mod).find(([k, v]) => k !== 'default' && /page$/i.test(k) && typeof v === 'function')?.[1] as
    | ComponentType<object>
    | undefined;
  const Comp = direct ?? fallback ?? pageLike;
  if (!Comp) throw new Error(\`页面未导出 \${exportName}\`);
  return { default: Comp };
}

const loaders: Record<string, () => Promise<{ default: ComponentType<object> }>> = {
${entries}
};

export function createLazyLegacyPage(componentField: string): LazyExoticComponent<ComponentType<object>> | null {
  const normalized = componentField.trim().replace(/^\\//, '').replace(/\\\\/g, '/').replace(/\\.tsx$/i, '');
  if (!normalized) return null;
  const id = normalized.endsWith('-page') ? normalized : \`\${normalized}-page\`;
  const loader = loaders[id];
  if (!loader) return null;
  return lazy(loader);
}

export function listLegacyPageIds(): string[] {
  return Object.keys(loaders).sort();
}
`;

fs.writeFileSync(OUT, content);
console.log(`Generated ${pageIds.length} page loaders → src/utils/legacy-page-registry.ts`);
